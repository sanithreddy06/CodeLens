const { test, expect } = require('@playwright/test');
const { makeZip } = require('../../server/test/zipFixture.cjs');
async function settings(page) {
  const menu = page.getByRole('button', { name: 'Projects & account' });
  if (await menu.isVisible() && await menu.getAttribute('aria-expanded') === 'false') await menu.click();
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Make it your workspace.' })).toBeVisible();
}
test('settings persist, follow the system, and change the actual source reader', async ({ page }, testInfo) => {
  await page.emulateMedia({ colorScheme: 'light' });
  await page.goto('/#signin');
  await page.getByLabel('Email address').fill(`${testInfo.project.name}@example.com`);
  await page.getByLabel('Password', { exact: true }).fill('browser-test-password');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page.locator('.project-name')).toHaveText('Your projects');
  await settings(page);
  await page.getByRole('button', { name: 'Dark theme' }).click();
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark');
  await expect(page.locator('.explorer-main')).toHaveCSS('background-color', 'rgb(22, 26, 35)');
  await page.getByRole('switch', { name: /Wrap long lines/ }).check();
  await page.getByRole('switch', { name: /Compact project history/ }).check();
  await page.getByRole('switch', { name: /Reduce motion/ }).check();
  await page.getByLabel('Code text size', { exact: false }).selectOption('16');
  await page.getByLabel('Default import source', { exact: false }).selectOption('zip');
  await page.reload();
  await expect(page.getByRole('button', { name: 'Dark theme' })).toHaveAttribute('aria-pressed', 'true');
  await expect(page.getByRole('switch', { name: /Wrap long lines/ })).toBeChecked();
  await expect(page.locator('html')).toHaveAttribute('data-compact', 'true');
  await expect(page.locator('html')).toHaveAttribute('data-reduce-motion', 'true');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('settings-dark.png'), fullPage: true });
  await page.getByRole('button', { name: 'Back to workspace' }).click();
  await expect(page.getByRole('radio', { name: 'Upload ZIP' })).toBeChecked();
  const name = `settings-${testInfo.project.name}.zip`;
  await page.locator('input[type=file]').setInputFiles({ name, mimeType: 'application/zip', buffer: makeZip({ 'index.js': `export const longLine = '${'sample '.repeat(60)}';\n` }) });
  await page.getByRole('button', { name: 'Analyze Project', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Structure', exact: true })).toBeVisible({ timeout: 20000 });
  await page.getByRole('button', { name: 'Structure', exact: true }).click();
  await page.getByRole('button', { name: 'index.js', exact: true }).click();
  await expect(page.locator('.source-code')).toHaveCSS('font-size', '16px');
  await expect(page.locator('.source-code')).toHaveCSS('white-space', 'pre-wrap');
  await expect(page.getByRole('dialog')).toContainText('export const longLine');
  await page.screenshot({ path: testInfo.outputPath('source-dark.png'), fullPage: true });
  await page.getByRole('button', { name: 'Close source viewer' }).click();
  await settings(page);
  await page.getByRole('button', { name: 'System theme' }).click();
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light');
  await page.emulateMedia({ colorScheme: 'dark' });
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark');
  await page.getByRole('button', { name: 'Light theme' }).click();
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light');
  await page.screenshot({ path: testInfo.outputPath('settings-light.png'), fullPage: true });
  await page.getByRole('button', { name: 'Reset preferences' }).click();
  await page.getByRole('button', { name: 'Restore defaults' }).click();
  await expect(page.getByRole('button', { name: 'System theme' })).toHaveAttribute('aria-pressed', 'true');
  await expect(page.getByRole('switch', { name: /Wrap long lines/ })).not.toBeChecked();
  await expect(page.getByLabel('Code text size', { exact: false })).toHaveValue('14');
  await page.getByRole('button', { name: 'Back to workspace' }).click();
  await expect(page.locator('.project-name')).toHaveText(`settings-${testInfo.project.name}`);
  const menu = page.getByRole('button', { name: 'Projects & account' });
  if (await menu.isVisible()) await menu.click();
  await page.getByRole('searchbox', { name: 'Search loaded projects' }).fill('nothing-matches-this-project');
  await expect(page.getByText('No matching projects in the loaded history.')).toBeVisible();
  await page.getByRole('searchbox', { name: 'Search loaded projects' }).fill(`settings-${testInfo.project.name}`);
  await expect(page.locator('.history-row')).toHaveCount(1);
  await page.locator('.sidebar-account').getByRole('button', { name: 'Sign out' }).click();
  await expect(page.getByRole('heading', { name: /Understand the code/ })).toBeVisible();
  await expect(page.locator('.marketing-site')).toHaveCSS('background-color', 'rgb(22, 26, 35)');
  await page.screenshot({ path: testInfo.outputPath('website-dark.png'), fullPage: true });
  await page.getByRole('link', { name: /Sign in/ }).first().click();
  await expect(page.locator('.signin-card')).toHaveCSS('background-color', 'rgb(22, 26, 35)');
});
